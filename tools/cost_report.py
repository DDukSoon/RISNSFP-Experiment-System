# -*- coding:utf-8 -*-
"""Combined report of Phase 2 build cost + Phase 3 runtime cost.

Inputs:
  participants/<pid>/build_cost.json          — generated by build_memory.py
  participants/<pid>/phase3/<cond>_log.json   — accumulated per turn by the Phase 3 server

Output:
  Console table (three-condition comparison: build wall-clock,
  scenario-generation cost, Phase 3 runtime tokens + latency)

Usage:
  python tools/cost_report.py -p P001
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_ROOT = _HERE.parent


def report(pid: str) -> None:
    pdir = _ROOT / "participants" / pid
    cost_path = pdir / "build_cost.json"
    if not cost_path.exists():
        print(f"Build cost file not found: {cost_path}")
        print(f"   Run `python build_memory.py -p {pid}` first.")
        return

    with cost_path.open(encoding="utf-8") as f:
        build_cost = json.load(f)

    print(f"  Cost report — participant {pid}")
    print(f"  Build time: {build_cost.get('timestamp', 'n/a')}")
    print(f"  Pipeline: {build_cost.get('pipeline', 'n/a')}")

    src = build_cost.get("source", {})
    print(f"  Source: {src.get('type', 'n/a')} "
          f"({src.get('total_turns', 0)} turns, {src.get('num_scenarios', 'n/a')} scenarios)")

    # ── Scenario generation cost (Gemini API) ───────────────────────
    sc_gen_sec = build_cost.get("scenario_generation_sec", None)
    usage = build_cost.get("gemini_usage", {})
    if sc_gen_sec is not None:
        print(f"\n[Scenario generation — Gemini API]")
        print(f"  wall-clock       : {sc_gen_sec}s"
              f"{'  (reused, no new call)' if sc_gen_sec < 1 else ''}")
        if "prompt_tokens" in usage:
            print(f"  model            : {usage.get('model', '?')}")
            print(f"  prompt tokens    : {usage['prompt_tokens']:,}")
            print(f"  completion tokens: {usage['completion_tokens']:,}")
            print(f"  total tokens     : {usage['total_tokens']:,}")
            print(f"  API call count   : {usage['call_count']}")
        elif "note" in usage:
            print(f"  note: {usage['note']}")

    # ── Per-condition build cost ─────────────────────────────────────────
    conds = build_cost.get("conditions", {})
    print(f"\n[Build cost by condition]")
    print(f"  {'condition':15s} {'wall-clock':>12s}")
    print(f"  {'-'*15} {'-'*12}")
    for cond_name in ("in_context", "retrieval", "parametric"):
        cd = conds.get(cond_name, {})
        wc = cd.get("wall_clock_sec", None)
        wc_str = f"{wc}s" if wc is not None else "n/a"
        print(f"  {cond_name:15s} {wc_str:>12s}")

    # ── Select the runtime data source ──────────────────────────────
    # Priority: CLI test results → actual Phase 3 server logs
    cli_path = pdir / "cli_test_results.json"
    phase3_dir = pdir / "phase3"

    if cli_path.exists():
        src_label = f"CLI test ({cli_path.name})"
        with cli_path.open(encoding="utf-8") as f:
            cli_doc = json.load(f)
        cli_results = cli_doc.get("results", {})

        def _get_turns(cond: str) -> list[dict]:
            # CLI format: [{q, a, ms, prompt_tokens, completion_tokens, total_tokens}, ...]
            rows = cli_results.get(cond, [])
            return [
                {
                    "usage": {
                        "llm_prompt_tokens": r.get("prompt_tokens", 0),
                        "llm_completion_tokens": r.get("completion_tokens", 0),
                    },
                    "latency": {"llm_ms": r.get("ms", 0)},
                }
                for r in rows
            ]
    else:
        src_label = "Phase 3 server logs (phase3/*_log.json)"

        def _get_turns(cond: str) -> list[dict]:
            logp = phase3_dir / f"{cond}_log.json"
            if not logp.exists():
                return []
            with logp.open(encoding="utf-8") as f:
                return json.load(f)

    print(f"\n[Phase 3 runtime (avg per query) — source: {src_label}]")
    print(f"  {'condition':15s} {'turns':>6s} {'prompt_tok':>12s} "
          f"{'compl_tok':>12s} {'llm_ms':>8s}")
    print(f"  {'-'*15} {'-'*6} {'-'*12} {'-'*12} {'-'*8}")

    for cond in ("in_context", "retrieval", "parametric"):
        turns = _get_turns(cond)
        if not turns:
            print(f"  {cond:15s} (no log)")
            continue
        n = len(turns)
        avg_p = sum(t["usage"]["llm_prompt_tokens"] for t in turns) / n
        avg_c = sum(t["usage"]["llm_completion_tokens"] for t in turns) / n
        avg_ms = sum(t["latency"]["llm_ms"] for t in turns) / n
        print(f"  {cond:15s} {n:>6d} {avg_p:>12.0f} {avg_c:>12.0f} {avg_ms:>8.0f}")
    print()


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    p = argparse.ArgumentParser(description="Combined Phase 2/3 cost report")
    p.add_argument("-p", "--pid", required=True, help="Participant ID (e.g. P001)")
    args = p.parse_args()
    report(args.pid)
